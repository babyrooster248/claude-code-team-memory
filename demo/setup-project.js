// Builds the sample project the demo and the cold/warm measurement both run against.
//
//   node demo/setup-project.js --dest ./demo-project --ingest https://host.example --project catalog-svc
//   node demo/setup-project.js --dest ./x --warm            # AGENTS.md already carries the entry
//
// Also usable as a module: require('./setup-project').build({ ... }).
//
// The traps are planted so they can only be found by DOING — running a script, reading a thrown
// error. A fact an agent can read off the README is exactly the fact this project refuses to store,
// so a demo built on README-derivable facts would be demonstrating the wrong thing.
//
// Two stacks. `--stack dotnet` copies demo/dotnet-template — a .NET 10 console app on EF Core 10 and
// SQLite, which is what the demo runs, because a trap a .NET team recognises is worth more than one
// that is merely true. The node stack is what demo/measure.js was measured on and is kept so those
// numbers stay reproducible.
//
// What is planted in each, and which candidates were dropped for failing to reproduce, is in
// demo/traps.md. Every trap there was run before it was written down.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

// The entry a real end-to-end run actually produced, reproduced verbatim. Used for the warm arm of
// the measurement and as the demo's starting state when replaying a later act on its own.

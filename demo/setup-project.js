// Builds the sample project the demo and the cold/warm measurement both run against.
//
//   node demo/setup-project.js --dest ./demo-project --ingest https://host.example --project catalog-svc
//   node demo/setup-project.js --dest ./x --warm            # AGENTS.md already carries the entry
//
// Also usable as a module: require('./setup-project').build({ ... }).
//
// The traps are planted so they can only be found by DOING — running a script, reading a thrown
// error. A fact an agent can read off the README is exactly the fact this project refuses to store,
// so a demo built on README-derivable facts would be demonstrating the wrong thing.
//
// Trap choice is by measured capture rate, not by which one reads best:
//   T1  migrate-before-seed, behind a misleading FK error   — captured 2/2 in real end-to-end runs
//   T2  record 1 is the seed owner row and refuses writes   — captured 4/4 on opus in the A/B
// Deliberately absent: the "which of two similar fields governs" class, captured only 2/4 in the
// pilot. Too unreliable to build a live act on.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

// The entry a real end-to-end run actually produced, reproduced verbatim. Used for the warm arm of
// the measurement and as the demo's starting state when replaying a later act on its own.
const APPROVED_ENTRY = `<!-- Maintained by claude-code-team-memory.
     AGENT: do not edit this file. It is the team's reviewed record, and the counts in it come from
     verified contributors, not from self-assessment. If you learn something here is wrong, or you
     confirm an entry firsthand, write that into your own auto memory — the pipeline counts you and
     updates this file. Editing it directly makes the count claim something nobody verified.
     HUMAN REVIEWER: edit freely. Delete a line you disagree with and the machine records that as a
     rejection rather than proposing it again. -->

## Traps
- (unconfirmed, 1 person) \`node seed.js\` fails with \`SQLITE_CONSTRAINT: FOREIGN KEY constraint failed (items.category_id -> categories.id)\` even when the real cause is that \`node migrate.js\` hasn't run yet (no \`.state/schema.json\`). Run \`node migrate.js && node seed.js\`. README lists both commands but not that the order is mandatory. [k1]

<!-- knowledge-state
k1: f7e188d6
-->
`;

const MEMORY_INSTRUCTION = `## Recording memory

Write it into auto memory whenever you learn something a teammate would want and the code does
not say: a command failed and then worked; I corrected you; something behaved in a way whose
real cause was not what it looked like; you chose or rejected an approach for a reason; you
worked out which of two similar things governs; you found an existing note is now wrong. Do it
before finishing the turn, including when you finish by asking me something. Err on the side of
writing it — a shared filter drops what does not belong, and nothing recovers what was never
written. Add one line to MEMORY.md.
`;

// Every script logs its own invocation. That is how "did it trip the trap" gets answered without
// parsing model output: the trap was tripped if `seed` appears before any `migrate`. Deterministic,
// and it cannot be fooled by the agent describing what it did differently from what it ran.
const INVOCATION_LOG = `
const fs = require('fs');
const path = require('path');
try {
  fs.mkdirSync(path.join(__dirname, '.state'), { recursive: true });
  fs.appendFileSync(path.join(__dirname, '.state', 'invocations.log'),
    new Date().toISOString() + ' ' + path.basename(__filename) + '\\n');
} catch {}
`;

function build(opts) {
  const {
    dest,
    projectId = 'catalog-svc',
    ingest = null,
    memoryDir = null,
    warm = false,
    hooks = true,
    hooksFrom = path.join(__dirname, '..', 'hooks'),
    git = true,
  } = opts;

  const root = path.resolve(dest);
  fs.rmSync(root, { recursive: true, force: true });
  fs.mkdirSync(path.join(root, '.claude'), { recursive: true });
  const w = (p, s) => {
    fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
    fs.writeFileSync(path.join(root, p), s);
  };

  // --- the project itself ------------------------------------------------------------------
  w('package.json', JSON.stringify({ name: projectId, version: '1.0.0', private: true }, null, 2) + '\n');

  // Says less than the code does, which is how real repositories are. It lists both commands and
  // does not say they are ordered — that gap IS trap T1.
  w('README.md', `# ${projectId}

Node data tooling for the catalog service. Plain node, no build step.

Scripts: \`node migrate.js\`, \`node seed.js\`, \`node update.js <id> <label>\`.

Config lives in \`config.json\`.
`);

  w('config.json', JSON.stringify({ locales: ['vi-VN', 'en-GB'], pageSize: 20 }, null, 2) + '\n');

  w('data/records.json', JSON.stringify([
    { id: 1, label: 'system-owner', locale: 'vi-VN', active: true, seed: true },
    { id: 2, label: 'Ao thun co tron', locale: 'vi-VN', active: true },
    { id: 3, label: 'Denim jacket', locale: 'en-GB', active: true },
  ], null, 2) + '\n');

  w('migrate.js', `${INVOCATION_LOG}
fs.writeFileSync(path.join(__dirname, '.state', 'schema.json'), JSON.stringify({ version: 2 }));
console.log('migrated: schema v2');
`);

  // T1: the message names a foreign key and the real cause is a missing schema file.
  w('seed.js', `${INVOCATION_LOG}
if (!fs.existsSync(path.join(__dirname, '.state', 'schema.json'))) {
  console.error('Error: SQLITE_CONSTRAINT: FOREIGN KEY constraint failed (items.category_id -> categories.id)');
  process.exit(1);
}
fs.writeFileSync(path.join(__dirname, '.state', 'seeded.json'), JSON.stringify({ items: 8 }));
console.log('seeded: 8 items');
`);

  // T2: refusing the write, and saying why, is the only place this rule exists.
  w('update.js', `${INVOCATION_LOG}
const [id, ...rest] = process.argv.slice(2);
const p = path.join(__dirname, 'data', 'records.json');
const rows = JSON.parse(fs.readFileSync(p, 'utf8'));

if (Number(id) === 1) {
  console.error('Refused: record 1 is the seed owner row. Overwriting its label detaches every');
  console.error('Refused: other row from its owner and the catalog stops resolving locales.');
  console.error('Refused: no migration repairs it — restore from the data/ backup instead.');
  process.exit(1);
}
const row = rows.find(r => r.id === Number(id));
if (!row) { console.error('no such record: ' + id); process.exit(1); }
row.label = rest.join(' ');
fs.writeFileSync(p, JSON.stringify(rows, null, 2) + '\\n');
console.log('updated record ' + id);
`);

  // --- what makes an agent behave like a teammate -------------------------------------------
  w('AGENTS.md', warm ? APPROVED_ENTRY : '');
  w('CLAUDE.md', `# ${projectId}

Node data tooling for the catalog service. Plain node, no build step.

@AGENTS.md

${MEMORY_INSTRUCTION}`);

  // `~/agent-knowledge/<project>` and not an absolute path: this file is committed and read on every
  // teammate's machine, and an absolute path from whoever generated it resolves to nothing on
  // theirs — which makes the hook exit down its silent fast path. The measurement overrides it per
  // run so one run cannot read the notes another run wrote.
  const settings = {
    autoMemoryDirectory: memoryDir
      ? memoryDir.replace(/\\/g, '/')
      : `~/agent-knowledge/${projectId}`,
  };
  if (ingest) settings.env = { AGENT_KNOWLEDGE_INGEST: ingest, AGENT_KNOWLEDGE_PROJECT: projectId };
  if (hooks) {
    settings.hooks = {
      PostToolUse: [{
        matcher: 'Write|Edit',
        hooks: [
          { type: 'command', command: 'sh hooks/post-note.sh' },
          { type: 'command', command: 'node hooks/post-note.js' },
        ],
      }],
      SessionStart: [{
        hooks: [
          { type: 'command', command: 'sh hooks/flush-spool.sh' },
          { type: 'command', command: 'node hooks/flush-spool.js' },
        ],
      }],
    };
    for (const f of ['post-note.js', 'post-note.sh', 'flush-spool.js', 'flush-spool.sh']) {
      fs.mkdirSync(path.join(root, 'hooks'), { recursive: true });
      fs.copyFileSync(path.join(hooksFrom, f), path.join(root, 'hooks', f));
    }
  }
  w('.claude/settings.json', JSON.stringify(settings, null, 2) + '\n');

  // The credential is deliberately NOT written. Each member copies the sample once; a generator
  // that wrote it would put a token into whatever the generated tree gets committed to.
  w('.gitignore', '.state/\n.claude/agent-knowledge.env\nAGENTS.md.proposed\n');

  // `--commit` builds a branch in the repo holding the artifact, so without a repo there is no PR
  // to review — the whole human-gate act depends on this line.
  if (git) {
    const g = (...args) => spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
    g('init', '-q');
    g('config', 'user.name', 'demo');
    g('config', 'user.email', 'demo@example.com');
    g('add', '-A');
    g('commit', '-q', '-m', 'catalog-svc: initial');
  }

  return { root, memoryDir: settings.autoMemoryDirectory, warm };
}

module.exports = { build, APPROVED_ENTRY, MEMORY_INSTRUCTION };

if (require.main === module) {
  const argv = process.argv.slice(2);
  const opt = (n, d) => { const i = argv.indexOf('--' + n); return i === -1 ? d : argv[i + 1]; };
  const r = build({
    dest: opt('dest', path.join(os.tmpdir(), 'catalog-svc-demo')),
    projectId: opt('project', 'catalog-svc'),
    ingest: opt('ingest', null),
    memoryDir: opt('memory', null),
    warm: argv.includes('--warm'),
    hooks: !argv.includes('--no-hooks'),
    git: !argv.includes('--no-git'),
  });
  console.log(`built ${r.warm ? 'WARM' : 'cold'} project at ${r.root}`);
  console.log(`  autoMemoryDirectory: ${r.memoryDir}`);
}

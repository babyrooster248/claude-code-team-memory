function build(opts) {
  const {
    dest,
    projectId = 'catalog-svc',
    ingest = null,
    memoryDir = null,
    warm = false,
    seeded = false,
    stack = 'node',
    hooks = true,
    hooksFrom = path.join(__dirname, '..', 'hooks'),
    git = true,
  } = opts;

  const root = path.resolve(dest);
  fs.rmSync(root, { recursive: true, force: true });
  fs.mkdirSync(path.join(root, '.claude'), { recursive: true });
  const w = (p, s) => {
    fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true });
    fs.writeFileSync(path.join(root, p), s);
  };

  // --- the project itself ------------------------------------------------------------------
  if (stack === 'dotnet') {
    // Copied from demo/dotnet-template rather than generated: these are real C# files that have to
    // compile, and a generator emitting C# from string templates is a generator nobody can debug.
    const tpl = path.join(__dirname, 'dotnet-template');
    const copy = (rel) => {
      const from = path.join(tpl, rel);
      for (const e of fs.readdirSync(from, { withFileTypes: true })) {
        const sub = path.join(rel, e.name);
        if (e.isDirectory()) { fs.mkdirSync(path.join(root, sub), { recursive: true }); copy(sub); }
        else fs.copyFileSync(path.join(tpl, sub), path.join(root, sub));
      }
    };
    fs.mkdirSync(root, { recursive: true });
    copy('.');
    writeClaudeFiles();
    if (git) initGit();
    return { root, memoryDir: settingsPath(), warm, stack };
  }

  w('package.json', JSON.stringify({ name: projectId, version: '1.0.0', private: true }, null, 2) + '\n');

  // Says less than the code does, which is how real repositories are. It lists both commands and
  // does not say they are ordered — that gap IS trap T1.
  w('README.md', `# ${projectId}

Node data tooling for the catalog service. Plain node, no build step.

Scripts: \`node migrate.js\`, \`node seed.js\`, \`node update.js <id> <label>\`.

Config lives in \`config.json\`.
`);

  w('config.json', JSON.stringify({ locales: ['vi-VN', 'en-GB'], pageSize: 20 }, null, 2) + '\n');

  w('data/records.json', JSON.stringify([
    { id: 1, label: 'system-owner', locale: 'vi-VN', active: true, seed: true },
    { id: 2, label: 'Ao thun co tron', locale: 'vi-VN', active: true },
    { id: 3, label: 'Denim jacket', locale: 'en-GB', active: true },
  ], null, 2) + '\n');

  w('migrate.js', `${INVOCATION_LOG}
fs.writeFileSync(path.join(__dirname, '.state', 'schema.json'), JSON.stringify({ version: 2 }));
console.log('migrated: schema v2');
`);

  // T1: the message names a foreign key and the real cause is a missing schema file.
  w('seed.js', `${INVOCATION_LOG}
if (!fs.existsSync(path.join(__dirname, '.state', 'schema.json'))) {
  console.error('Error: SQLITE_CONSTRAINT: FOREIGN KEY constraint failed (items.category_id -> categories.id)');
  process.exit(1);
}
fs.writeFileSync(path.join(__dirname, '.state', 'seeded.json'), JSON.stringify({ items: 8 }));
console.log('seeded: 8 items');
`);

  // T2: refusing the write, and saying why, is the only place this rule exists.
  w('update.js', `${INVOCATION_LOG}
const [id, ...rest] = process.argv.slice(2);
const p = path.join(__dirname, 'data', 'records.json');
const rows = JSON.parse(fs.readFileSync(p, 'utf8'));

if (Number(id) === 1) {
  console.error('Refused: record 1 is the seed owner row. Overwriting its label detaches every');
  console.error('Refused: other row from its owner and the catalog stops resolving locales.');
  console.error('Refused: no migration repairs it — restore from the data/ backup instead.');
  process.exit(1);
}
const row = rows.find(r => r.id === Number(id));
if (!row) { console.error('no such record: ' + id); process.exit(1); }
row.label = rest.join(' ');
fs.writeFileSync(p, JSON.stringify(rows, null, 2) + '\\n');
console.log('updated record ' + id);
`);

  writeClaudeFiles();
  if (git) initGit();
  return { root, memoryDir: settingsPath(), warm, stack };

  // ---- shared by both stacks -----------------------------------------------------------------

  // `~/agent-knowledge/<project>` and not an absolute path: this file is committed and read on every
  // teammate's machine, and an absolute path from whoever generated it resolves to nothing on theirs,
  // which makes the hook exit down its silent fast path. The measurement overrides it per run so one
  // run cannot read the notes another run wrote.
  function settingsPath() {
    return memoryDir ? memoryDir.replace(/\\/g, '/') : `~/agent-knowledge/${projectId}`;
  }

  function writeClaudeFiles() {
    w('AGENTS.md', seeded ? SEEDED_ARTIFACT : (warm ? APPROVED_ENTRY : ''));

    const summary = stack === 'dotnet'
      ? '.NET 10 console tooling for the catalog service. EF Core 10 on SQLite, no database server.'
      : 'Node data tooling for the catalog service. Plain node, no build step.';
    w('CLAUDE.md', `# ${projectId}\n\n${summary}\n\n@AGENTS.md\n\n${MEMORY_INSTRUCTION}`);

    const settings = { autoMemoryDirectory: settingsPath() };
    if (ingest) settings.env = { AGENT_KNOWLEDGE_INGEST: ingest, AGENT_KNOWLEDGE_PROJECT: projectId };
    if (hooks) {
      settings.hooks = {
        PostToolUse: [{
          matcher: 'Write|Edit',
          hooks: [
            { type: 'command', command: 'sh hooks/post-note.sh' },
            { type: 'command', command: 'node hooks/post-note.js' },
          ],
        }],
        SessionStart: [{
          hooks: [
            { type: 'command', command: 'sh hooks/flush-spool.sh' },
            { type: 'command', command: 'node hooks/flush-spool.js' },
          ],
        }],
      };
      fs.mkdirSync(path.join(root, 'hooks'), { recursive: true });
      for (const f of ['post-note.js', 'post-note.sh', 'flush-spool.js', 'flush-spool.sh']) {
        fs.copyFileSync(path.join(hooksFrom, f), path.join(root, 'hooks', f));
      }
    }
    w('.claude/settings.json', JSON.stringify(settings, null, 2) + '\n');

    // The credential is deliberately NOT written. Each member copies the sample once; a generator
    // that wrote it would put a token into whatever the generated tree gets committed to.
    w('.gitignore', [
      '.state/', '.claude/agent-knowledge.env', 'AGENTS.md.proposed',
      'bin/', 'obj/', '*.db', '*.db-shm', '*.db-wal', '',
    ].join('\n'));
  }

  // `--commit` builds a branch in the repo holding the artifact, so without a repo there is no PR to
  // review — the whole human-gate act depends on this line.
  function initGit() {
    const g = (...args) => spawnSync('git', ['-C', root, ...args], { encoding: 'utf8' });
    g('init', '-q');
    g('config', 'user.name', 'demo');
    g('config', 'user.email', 'demo@example.com');
    g('add', '-A');
    g('commit', '-q', '-m', `${projectId}: initial`);
  }
}

module.exports = { build, APPROVED_ENTRY, MEMORY_INSTRUCTION };

if (require.main === module) {
  const argv = process.argv.slice(2);
  const opt = (n, d) => { const i = argv.indexOf('--' + n); return i === -1 ? d : argv[i + 1]; };
  const r = build({
    dest: opt('dest', path.join(os.tmpdir(), 'catalog-svc-demo')),
    projectId: opt('project', 'catalog-svc'),
    ingest: opt('ingest', null),
    memoryDir: opt('memory', null),
    stack: opt('stack', 'node'),
    warm: argv.includes('--warm'),
    seeded: argv.includes('--seeded'),
    hooks: !argv.includes('--no-hooks'),
    git: !argv.includes('--no-git'),
  });
  console.log(`built ${r.stack} project at ${r.root}` +
    ` (AGENTS.md: ${argv.includes('--seeded') ? 'pre-seeded, 3 entries' : r.warm ? 'one entry' : 'empty'})`);
  console.log(`  autoMemoryDirectory: ${r.memoryDir}`);
}
